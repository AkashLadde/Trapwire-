def seed(count: int = 0) -> None:
    database.init_db()
    for o in SYNTHETIC_SAMPLE_ORDERS:
        database.db_save_order(o)
    for idx in range(count):
        suffix = "".join(random.choices(string.digits, k=4))
        database.db_save_order({
            "order_id": f"ORD-SYN-{suffix}",
            "customer_name": f"Synthetic Sample {idx + 1}",
            "phone": f"+91 90000{suffix.zfill(5)}",
            "email": f"synthetic.{suffix}@example.test",
            "aadhaar": f"0000-0000-{suffix}",
            "pan": f"SYNTH{suffix}Z",
            "address": "Synthetic Demo Address, India",
            "card_last4": suffix,
            "item": "Sample Security Item",
            "order_value": float(random.randint(500, 15000)),
            "status": "Delivered",
        })
    for u in SYNTHETIC_SAMPLE_USERS:
        database.db_save_user(u)
    existing_projects = {p["name"] for p in database.db_get_projects()}
    for p in SYNTHETIC_SAMPLE_PROJECTS:
        if p["name"] not in existing_projects:
            database.db_save_project(p)
    print(f"[SEED] Inserted synthetic sample records into {database.DB_ENGINE} database.")


def clear() -> None:
    database.init_db()
    for o in SYNTHETIC_SAMPLE_ORDERS:
        database.db_delete_order(o["order_id"])
    for o in database.db_get_orders():
        if o["order_id"].startswith("ORD-SYN-"):
            database.db_delete_order(o["order_id"])
    for u in SYNTHETIC_SAMPLE_USERS:
        database.db_delete_user(u["email"])
    for p in database.db_get_projects():
        if "(Sample)" in p["name"]:
            database.db_delete_project(p["id"])
    print("[SEED] Cleared synthetic sample records.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Optional synthetic demo seeder for TRAPWIRE")
    parser.add_argument("--clear", action="store_true", help="Remove synthetic sample records")
    parser.add_argument("--extra", type=int, default=0, help="Insert N extra synthetic sample orders")
    args = parser.parse_args()
    if args.clear:
        clear()
    else:
        seed(count=args.extra)

